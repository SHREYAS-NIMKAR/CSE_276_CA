export function escapeCsvCell(value: unknown): string {
  const str = value === null || value === undefined ? '' : String(value);
  // Neutralize formula injection (=, +, -, @, \t, \r)
  const neutralized = /^[=+\-@\t\r]/.test(str) ? `'${str}` : str;
  if (/[",\n\r]/.test(neutralized)) {
    return `"${neutralized.replace(/"/g, '""')}"`;
  }
  return neutralized;
}

export function buildCsv(headers: string[], rows: unknown[][], bannerComment?: string): string {
  const lines: string[] = [];
  if (bannerComment) {
    lines.push(escapeCsvCell(bannerComment));
  }
  lines.push(headers.map(escapeCsvCell).join(','));
  for (const row of rows) {
    lines.push(row.map(escapeCsvCell).join(','));
  }
  return lines.join('\n');
}

export async function generateProjectReportPdf(params: {
  project: ProjectRecord;
  assessment: AssessmentResult;
  exceptions: ExceptionRecord[];
  riskAcceptances: RiskAcceptanceRecord[];
  comments: ReviewCommentRecord[];
  generatedBy: UserRecord;
}): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 46, size: 'A4' });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const { project, assessment, exceptions, riskAcceptances, comments, generatedBy } = params;
    const generatedAt = new Date().toISOString();

    if (project.is_demo) {
      doc
        .rect(46, 36, 503, 24)
        .fill('#FEF3C7')
        .fillColor('#92400E')
        .fontSize(9)
        .font('Helvetica-Bold')
        .text(
          'DEMONSTRATION DATA: not real institutional approvals or governance decisions.',
          54,
          44
        );
      doc.moveDown(1.8);
    }

    doc
      .fillColor('#0B2545')
      .fontSize(18)
      .font('Helvetica-Bold')
      .text('AI Development Lifecycle Governance Report');

    doc
      .fontSize(10)
      .font('Helvetica')
      .fillColor('#334155')
      .text(`Project: ${project.name}${project.is_demo ? ' [DEMO]' : ''}`)
      .text(`Owner: ${project.owner_name ?? project.owner_id} | Reviewer: ${project.reviewer_name ?? project.assigned_reviewer_id}`)
      .text(
        `Workflow State: ${project.workflow_state} | Autonomy: ${project.deployment_autonomy} | Sensitivity: ${project.data_sensitivity}`
      )
      .text(`Generated By: ${generatedBy.full_name} (${generatedBy.role}) at ${generatedAt}`)
      .text(`Assessment Run: ${assessment.runId} (${assessment.evaluatedAt})`)
      .moveDown(0.8);

    // Summary Status Box
    doc
      .fontSize(12)
      .font('Helvetica-Bold')
      .fillColor(assessment.releaseLocked ? '#991B1B' : '#065F46')
      .text(`Status: ${assessment.releaseStatusBanner}`);
    doc
      .fontSize(10)
      .font('Helvetica')
      .fillColor('#1E293B')
      .text(assessment.releaseStatusSentence)
      .text(
        `Overall Readiness: ${(assessment.overallReadiness * 100).toFixed(1)}% (${assessment.readinessLabel}) | Stages Complete: ${assessment.stagesCompleteCount}/6 | High Risks Open: ${assessment.highRiskOpenCount}`
      )
      .moveDown(0.8);

    if (assessment.releaseLockedReasons.length > 0) {
      doc.font('Helvetica-Bold').fontSize(11).fillColor('#0B2545').text('Release Lock Reasons');
      doc.font('Helvetica').fontSize(9).fillColor('#334155');
      for (const reason of assessment.releaseLockedReasons) {
        doc.text(`- ${reason}`);
      }
      doc.moveDown(0.6);
    }

    // Stage Table
    doc.font('Helvetica-Bold').fontSize(12).fillColor('#0B2545').text('1. Lifecycle Stages & Gates');
    doc.moveDown(0.3);
    for (const s of assessment.stageSummaries) {
      doc
        .font('Helvetica-Bold')
        .fontSize(10)
        .fillColor('#0F172A')
        .text(
          `Stage ${s.stage}: ${s.name} — Rs ${(s.rs * 100).toFixed(0)}% | Raw Gate Gs=${s.gs} | Effective Gate=${s.effectiveGs} | ${s.statusWord}${s.scoreHighButGateLocked ? ' (Score high but gate locked)' : ''}`
        );
      doc.font('Helvetica').fontSize(9).fillColor('#475569');
      const missing = s.artefactDetails.filter((a) => a.classification !== 'Verified');
      if (missing.length === 0) {
        doc.text('   All artefacts verified and in date.');
      } else {
        for (const m of missing) {
          doc.text(
            `   • ${m.name} (${m.isBlocking ? 'Blocking' : 'Advisory'}): ${m.classification}${m.coveredByExceptionId ? ` [Covered by ${m.coveredByExceptionId}]` : ''}`
          );
        }
      }
    }
    doc.moveDown(0.7);

    // Risks
    doc.font('Helvetica-Bold').fontSize(12).fillColor('#0B2545').text('2. Governance Risks');
    doc.font('Helvetica').fontSize(9).fillColor('#334155');
    const activeRisks = assessment.riskSummaries.filter((r) => r.status !== 'Mitigated');
    if (activeRisks.length === 0) {
      doc.text('No open governance risks.');
    } else {
      for (const r of activeRisks) {
        doc.text(
          `- [${r.severity}] ${r.name} (${r.riskId}) — Status: ${r.status} | Rules: ${r.triggeringRuleIds.join(', ') || 'None'}`
        );
      }
    }
    doc.moveDown(0.7);

    // Rule Execution Trace
    doc.font('Helvetica-Bold').fontSize(12).fillColor('#0B2545').text('3. Rule Engine Execution Trace');
    doc.font('Helvetica').fontSize(9).fillColor('#334155');
    if (assessment.firedRules.length === 0) {
      doc.text('No rules fired.');
    } else {
      for (const fr of assessment.firedRules) {
        doc.text(`${fr.step}. [${fr.ruleId} | ${fr.ruleType}] ${fr.ruleName}: ${fr.outcome}`);
      }
    }
    doc.moveDown(0.7);

    // Grounded Guidance with Citations
    doc.font('Helvetica-Bold').fontSize(12).fillColor('#0B2545').text('4. Policy-Grounded Guidance');
    doc.font('Helvetica').fontSize(9).fillColor('#334155');
    if (assessment.guidanceItems.length === 0) {
      doc.text('No remediation guidance items triggered.');
    } else {
      for (const g of assessment.guidanceItems) {
        const top = g.clauses[0];
        doc.text(
          `- (${g.ruleId}) ${g.plainHeadline} | Confidence: ${g.topConfidence}${top ? ` | Citation: ${top.clauseId} (${top.source}, Sec. ${top.sectionNumber})` : ''}`
        );
        doc.fillColor('#475569').text(`  ${g.howToFixFromPolicy}`).fillColor('#334155');
      }
    }
    doc.moveDown(0.7);

    // Exceptions & Risk Acceptances
    doc.font('Helvetica-Bold').fontSize(12).fillColor('#0B2545').text('5. Exceptions & Formal Risk Acceptances');
    doc.font('Helvetica').fontSize(9).fillColor('#334155');
    if (exceptions.length === 0 && riskAcceptances.length === 0) {
      doc.text('No exceptions or formal risk acceptances recorded.');
    } else {
      for (const ex of exceptions) {
        doc.text(
          `- Exception ${ex.id} (${ex.status}): ${ex.target_type} ${ex.target_id} | Expires ${ex.expiry_date.slice(0, 10)} | Rationale: ${ex.rationale}`
        );
      }
      for (const ra of riskAcceptances) {
        doc.text(
          `- Formal Acceptance ${ra.id} (${ra.status}): Risk ${ra.risk_id} | Approver: ${ra.approver_name ?? ra.approver_id} | Expires ${ra.expiry_date.slice(0, 10)} | Scope: ${ra.scope}`
        );
      }
    }
    doc.moveDown(0.7);

    // Review Comments & Sign-Off
    doc.font('Helvetica-Bold').fontSize(12).fillColor('#0B2545').text('6. Human Review & Sign-Off Record');
    doc.font('Helvetica').fontSize(9).fillColor('#334155');
    if (comments.length === 0) {
      doc.text('No human review entries recorded yet.');
    } else {
      for (const c of comments) {
        doc.text(`- [${c.created_at.slice(0, 16)}] ${c.author_name ?? c.author_id} (${c.action_type}): ${c.comment}`);
      }
    }

    doc.moveDown(1);
    doc
      .fontSize(8)
      .fillColor('#64748B')
      .text('This tool supports human governance boards and does not replace them.');

    doc.end();
  });
}

